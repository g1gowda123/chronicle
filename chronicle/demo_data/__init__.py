"""Bundled, model-free SQLite memory used by ``chronicle ask``.

The database is generated by ``chronicle demo --db <path> --force`` from the
geometric scene in :mod:`chronicle.demo`.  Keeping it inside the package makes
the read path usable immediately after a core-only install, without cloning the
repository or downloading a video.
"""

from __future__ import annotations

from importlib.resources import files
from pathlib import Path


def demo_db_path() -> Path:
    """Return the filesystem path of the bundled demo memory."""

    path = Path(str(files(__package__).joinpath("demo.db")))
    if not path.is_file():
        raise FileNotFoundError(
            "The bundled demo memory is missing. Reinstall Chronicle or run "
            "`chronicle demo --db chronicle/demo_data/demo.db --force`."
        )
    return path


__all__ = ["demo_db_path"]
